CREATE SCHEMA attendance;
CREATE SCHEMA reporting;
CREATE SCHEMA attendance_jobs;
CREATE SCHEMA reporting_jobs;
CREATE ROLE attendance_runtime LOGIN PASSWORD 'journey-only' NOSUPERUSER NOBYPASSRLS;
CREATE ROLE reporting_runtime LOGIN PASSWORD 'journey-only' NOSUPERUSER NOBYPASSRLS;
CREATE ROLE attendance_job LOGIN PASSWORD 'journey-only' NOSUPERUSER NOBYPASSRLS;
CREATE ROLE reporting_job LOGIN PASSWORD 'journey-only' NOSUPERUSER NOBYPASSRLS;
GRANT USAGE ON SCHEMA attendance TO attendance_runtime;
GRANT USAGE ON SCHEMA reporting TO reporting_runtime;
GRANT USAGE ON SCHEMA attendance_jobs TO attendance_job;
GRANT USAGE ON SCHEMA reporting_jobs TO reporting_job;
ALTER DEFAULT PRIVILEGES IN SCHEMA attendance GRANT SELECT,INSERT,UPDATE,DELETE ON TABLES TO attendance_runtime;
ALTER DEFAULT PRIVILEGES IN SCHEMA attendance GRANT USAGE,SELECT ON SEQUENCES TO attendance_runtime;
ALTER DEFAULT PRIVILEGES IN SCHEMA reporting GRANT SELECT,INSERT,UPDATE,DELETE ON TABLES TO reporting_runtime;
ALTER DEFAULT PRIVILEGES IN SCHEMA attendance_jobs GRANT SELECT ON TABLES TO attendance_job;
ALTER DEFAULT PRIVILEGES IN SCHEMA reporting_jobs GRANT SELECT ON TABLES TO reporting_job;

